import { describe, it, expect } from "vitest";
import { normalizePhone } from "./phone";

// 規格 5.6：重複電話比對用的正規化
describe("normalizePhone 電話正規化", () => {
  it.each([
    ["0912345678", "0912345678"],
    ["0912-345-678", "0912345678"],
    ["0912 345 678", "0912345678"],
    ["+886 912 345 678", "0912345678"],
    ["+886-912-345-678", "0912345678"],
    ["+886-2-2345-6789", "0223456789"],
    ["(02)2345-6789", "0223456789"],
    ["(02)2345-6789#123", "0223456789"],
    ["02-23456789 轉 123", "0223456789"],
    ["02-23456789轉123", "0223456789"],
    ["02-23456789 ext 12", "0223456789"],
    ["02-23456789 EXT.12", "0223456789"],
    ["  0912345678  ", "0912345678"],
  ])("%s → %s", (raw, expected) => {
    expect(normalizePhone(raw)).toBe(expected);
  });

  it("同一支電話不同寫法比對結果相同", () => {
    expect(normalizePhone("+886 912-345-678")).toBe(normalizePhone("0912 345 678"));
  });

  it("保留開頭 0，不轉成數字", () => {
    expect(normalizePhone("0800-000-123").startsWith("0")).toBe(true);
  });
});
